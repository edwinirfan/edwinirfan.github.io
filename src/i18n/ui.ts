/** Prefix a site path with the language segment (Indonesian is the default, unprefixed). */
export const localePath = (lang: Lang, path = '/') => {
  const clean = path.startsWith('/') ? path : `/${path}`;
  return lang === 'id' ? clean : `/en${clean === '/' ? '/' : clean}`;
};

